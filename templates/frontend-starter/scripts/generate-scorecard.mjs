#!/usr/bin/env node
/**
 * Executive Test Scorecard Generator
 * Parses Playwright test results and outputs a branded Markdown scorecard (test-summary.md).
 */

import fs from 'fs';
import path from 'path';

const resultsPath = path.resolve(process.cwd(), 'test-results', 'results.json');
const outputPath = path.resolve(process.cwd(), 'test-summary.md');

if (!fs.existsSync(resultsPath)) {
  console.log('No test-results/results.json found. Run `npm run test:e2e` first.');
  process.exit(0);
}

try {
  const data = JSON.parse(fs.readFileSync(resultsPath, 'utf8'));
  const total = data.suites?.reduce((acc, s) => acc + (s.specs?.length || 0), 0) || 0;
  let passed = 0;
  let failed = 0;

  const rows = [];
  data.suites?.forEach((suite) => {
    suite.specs?.forEach((spec) => {
      const isPass = spec.tests?.every((t) => t.status === 'expected');
      if (isPass) passed++;
      else failed++;
      rows.push(`| \`${spec.title}\` | ${isPass ? '✅ Passed' : '❌ Failed'} | \`${spec.file}\` |`);
    });
  });

  const markdown = `# Enterprise Quality & Accessibility Audit Scorecard

> **Target Application**: Enterprise Next.js Application  
> **Evaluation Standards**: WCAG 2.1 Level AA, IBM Carbon / DTCG Compliance, Zero Regressions  
> **Timestamp**: ${new Date().toISOString()}  

---

## 📊 Summary of Test Results

| Metric | Value | Status |
|---|---|---|
| **Total Test Specs** | \`${total}\` | 🎯 Evaluated |
| **Passing Specs** | \`${passed}\` | ${passed === total ? '✅ 100% Passed' : '⚠️ Attention Required'} |
| **Failed Specs** | \`${failed}\` | ${failed === 0 ? '✅ 0 Failures' : '❌ ' + failed + ' Violations'} |
| **WCAG 2.1 AA Compliance** | ${failed === 0 ? '**100% Verified**' : '**Deficiencies Found**'} | ${failed === 0 ? '🏆 Gold Standard' : '⚠️ Action Required'} |

---

## 🧪 Detailed Test Execution Matrix

| Test Specification | Status | Location |
|---|---|---|
${rows.length > 0 ? rows.join('\n') : '| *No test specs detected* | - | - |'}

---

*Report automatically generated by the Enterprise Design System FastMCP Engine.*
`;

  fs.writeFileSync(outputPath, markdown, 'utf8');
  console.log(`✅ Executive scorecard written to: ${outputPath}`);
} catch (err) {
  console.error('Error generating scorecard:', err.message);
}
